use serde_json::{Value, json};

enum V {
    I(i64),
    F(f64),
    S(&'static str),
    J(Value),
}

fn fb(x: f64) -> Value {
    json!({"bits": x.to_bits()})
}

/// The composite constants, encoded the way the generator encodes them.
fn composite(name: &str) -> Value {
    match name {
        "OBSTACLE_CUE_HARMONICS" => Value::Array(
            OBSTACLE_CUE_HARMONICS
                .iter()
                .map(|(h, a)| json!([h, fb(*a)]))
                .collect(),
        ),
        "OBSTACLE_ADVISORY_RATE" => {
            json!([fb(OBSTACLE_ADVISORY_RATE.0), fb(OBSTACLE_ADVISORY_RATE.1)])
        }
        "OBSTACLE_URGENT_RATE" => json!([fb(OBSTACLE_URGENT_RATE.0), fb(OBSTACLE_URGENT_RATE.1)]),
        "SLIDE_BAND_LO" => json!([fb(SLIDE_BAND_LO.0), fb(SLIDE_BAND_LO.1)]),
        "SLIDE_BAND_HI" => json!([fb(SLIDE_BAND_HI.0), fb(SLIDE_BAND_HI.1)]),
        "PLACEMENT_PING_RUNGS" => Value::Array(
            PLACEMENT_PING_RUNGS
                .iter()
                .map(|r| json!([fb(r.0), fb(r.1), fb(r.2), fb(r.3), fb(r.4)]))
                .collect(),
        ),
        "SCAN_PYTHAGOREAN_RATIOS" => {
            Value::Array(SCAN_PYTHAGOREAN_RATIOS.iter().map(|x| fb(*x)).collect())
        }
        "SCAN_OBJECT_HARMONICS" => json!(SCAN_OBJECT_HARMONICS),
        "SCAN_ICE_PARTIALS" => Value::Array(
            SCAN_ICE_PARTIALS
                .iter()
                .map(|(m, db)| json!([fb(*m), fb(*db)]))
                .collect(),
        ),
        "SCAN_FAMILY_CODES" => Value::Array(
            SCAN_FAMILY_CODES
                .iter()
                .map(|(k, v)| json!([k, v]))
                .collect(),
        ),
        "SCAN_FAMILY_VOICES" => {
            let mut v: Vec<&str> = SCAN_FAMILY_VOICES.to_vec();
            v.sort();
            json!(v)
        }
        "SCAN_POI_PARTIALS" => Value::Array(SCAN_POI_PARTIALS.iter().map(|x| fb(*x)).collect()),
        other => panic!("no composite encoding for {other}"),
    }
}

/// Floats inside a fixture value compared by bits only (the repr is for humans).
fn same_json(a: &Value, b: &Value) -> bool {
    match (a, b) {
        (Value::Object(x), Value::Object(_)) if x.contains_key("bits") => same_f64(f(a), f(b)),
        (Value::Array(x), Value::Array(y)) => {
            x.len() == y.len() && x.iter().zip(y).all(|(p, q)| same_json(p, q))
        }
        _ => a == b,
    }
}

