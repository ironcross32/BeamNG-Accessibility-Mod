"""Key names as the `keyboard` package produces them, for the E5 keyboard module.

Writes two things:

* ``rust/crates/beam-engine/src/keyboard/canonical_names.rs``: the package's
  ``canonical_names`` table, verbatim and in order, which ``normalize_name`` applies to
  every event name and every name a hook is registered under.
* ``rust/fixtures/data/keyboard_names.json``: what this machine's keyboard layout makes of
  a table of keys (``key_to_scan_codes`` and the event name a key press would carry), so
  the Rust replica of ``_winkeyboard``'s name tables can be checked against the real one.
  The names depend on the active layout, so the layout handle is recorded and the Rust
  test skips the comparison under a different layout.

No hook is installed: ``key_to_scan_codes`` only builds the name tables.

    uv run python rust/fixtures/gen/keyboard_names.py
"""

from __future__ import annotations

import ctypes
import os

import _common
from _common import write_fixture

from keyboard import _canonical_names, _winkeyboard
from keyboard import key_to_scan_codes

RS_PATH = os.path.join(
    _common.RUST_DIR, "crates", "beam-engine", "src", "keyboard", "canonical_names.rs"
)


def rust_str(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= o < 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%x}" % o)
    return '"' + "".join(out) + '"'


def write_canonical_rs():
    lines = [
        "//! `keyboard._canonical_names.canonical_names`, verbatim and in the package's order.",
        "//!",
        "//! Generated by `rust/fixtures/gen/keyboard_names.py`; do not edit by hand.",
        "",
        "pub(crate) static CANONICAL_NAMES: &[(&str, &str)] = &[",
    ]
    for k, v in _canonical_names.canonical_names.items():
        lines.append(f"    ({rust_str(k)}, {rust_str(v)}),")
    lines.append("];")
    with open(RS_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(RS_PATH, _common.REPO_ROOT)}")


MOD_BITS = {"shift": 1, "alt gr": 2, "num lock": 4, "caps lock": 8, "scroll lock": 16}
MOD_SETS = [(), ("shift",), ("num lock",), ("shift", "num lock"), ("caps lock",),
            ("scroll lock",), ("num lock", "caps lock")]

HOOK_KEYS = [
    "up", "down", "left", "right", "escape", "esc", "enter", "[", "]", "space", "f9",
    "f10", "f11", "shift", "ctrl", "alt", "tab", "a", "A", "1", "!", "+", "=", "-", "0",
    "x", "m", "t", "page up", "page down", "home", "end", "delete", "backspace",
    "left shift", "right ctrl", "windows", "no such key",
]

NORMALIZE = ["Up", "A", "a", "LEFT CONTROL", "left_ctrl", "_", "Num 8", " ", "\t", "Esc",
             "escape", "Right Alt", "é", "ÉCLAIR", "spacebar", "Return", "x_y"]


def event_name(scan, vk, ext, mods):
    entry = (scan, vk, ext, mods)
    if entry not in _winkeyboard.to_name:
        _winkeyboard.to_name[entry] = list(_winkeyboard.get_event_names(*entry))
    names = _winkeyboard.to_name[entry]
    if not names:
        return None
    return _canonical_names.normalize_name(names[0])


def main():
    write_canonical_rs()

    codes = {}
    for key in HOOK_KEYS:
        try:
            codes[key] = {"ok": list(key_to_scan_codes(key))}
        except ValueError as exc:
            codes[key] = {"err": str(exc)}

    user32 = ctypes.windll.user32
    events = []
    for vk in range(1, 0x100):
        scan = user32.MapVirtualKeyW(vk, 0)
        if scan == 0:
            continue
        for ext in (0, 1):
            for mods in MOD_SETS:
                bits = sum(MOD_BITS[m] for m in mods)
                events.append([scan, vk, ext, bits, event_name(scan, vk, ext, mods)])

    layout = user32.GetKeyboardLayout(0) & 0xFFFFFFFF
    write_fixture(
        "keyboard_names",
        {
            "layout": layout,
            "key_to_scan_codes": codes,
            "events": events,
            "normalize": [[n, _canonical_names.normalize_name(n)] for n in NORMALIZE],
        },
    )


if __name__ == "__main__":
    main()
