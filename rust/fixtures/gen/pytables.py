"""Generate beam-reports' Python-semantics tables from the running CPython.

Writes ``rust/crates/beam-reports/src/pytables.in.rs`` (included by ``pyops.rs``):

* ``HTML5_ENTITIES``: ``html.entities.html5``, sorted by name, for ``html.unescape``.
* ``INVALID_CHARREFS`` / ``INVALID_CODEPOINTS``: ``html._invalid_charrefs`` and
  ``html._invalid_codepoints``.
* ``DECIMAL_ZEROS``: the code point of each Unicode decimal-digit run's zero. Python's
  ``re`` ``\\d``, ``int(str)`` and ``float(str)`` all accept category Nd digits.
* ``NON_PRINTABLE``: inclusive ranges where ``str.isprintable()`` is false, for ``repr``.

Run from the repository root: ``uv run python rust/fixtures/gen/pytables.py``.
"""

from __future__ import annotations

import html
import html.entities
import os
import sys
import unicodedata

from _common import RUST_DIR

OUT = os.path.join(RUST_DIR, "crates", "beam-reports", "src", "pytables.in.rs")


def lit(s):
    out = []
    for ch in s:
        cp = ord(ch)
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{cp:x}}}")
    return '"' + "".join(out) + '"'


def main():
    lines = [
        "// Generated by rust/fixtures/gen/pytables.py from CPython "
        + sys.version.split()[0]
        + " (unicodedata "
        + unicodedata.unidata_version
        + "). Do not edit.",
        "",
    ]

    ents = sorted(html.entities.html5.items(), key=lambda kv: kv[0].encode("utf-8"))
    lines.append("pub(crate) static HTML5_ENTITIES: &[(&str, &str)] = &[")
    for k, v in ents:
        lines.append(f"    ({lit(k)}, {lit(v)}),")
    lines.append("];")
    lines.append("")

    lines.append("pub(crate) static INVALID_CHARREFS: &[(u32, &str)] = &[")
    for k, v in sorted(html._invalid_charrefs.items()):
        lines.append(f"    ({k}, {lit(v)}),")
    lines.append("];")
    lines.append("")
    lines.append("pub(crate) static INVALID_CODEPOINTS: &[u32] = &[")
    for k in sorted(html._invalid_codepoints):
        lines.append(f"    {k},")
    lines.append("];")
    lines.append("")

    zeros = []
    covered = set()
    for cp in range(0x110000):
        ch = chr(cp)
        if unicodedata.category(ch) == "Nd" and unicodedata.decimal(ch, None) == 0:
            zeros.append(cp)
            for d in range(10):
                assert unicodedata.decimal(chr(cp + d), None) == d, hex(cp)
                covered.add(cp + d)
    for cp in range(0x110000):
        ch = chr(cp)
        is_digit = unicodedata.decimal(ch, None) is not None
        assert is_digit == (cp in covered), hex(cp)
        assert (unicodedata.category(ch) == "Nd") == is_digit, hex(cp)
    lines.append("pub(crate) static DECIMAL_ZEROS: &[u32] = &[")
    for z in zeros:
        lines.append(f"    0x{z:x},")
    lines.append("];")
    lines.append("")

    ranges = []
    start = None
    for cp in range(0x110001):
        np_ = cp < 0x110000 and not chr(cp).isprintable()
        if np_ and start is None:
            start = cp
        elif not np_ and start is not None:
            ranges.append((start, cp - 1))
            start = None
    lines.append("pub(crate) static NON_PRINTABLE: &[(u32, u32)] = &[")
    for a, b in ranges:
        lines.append(f"    (0x{a:x}, 0x{b:x}),")
    lines.append("];")

    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
